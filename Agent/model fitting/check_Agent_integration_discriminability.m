%% ========================================================================
%  Local functions
%  ========================================================================
function [recoded_reward, q_0_0_trace] = local_generate_world1_fixed(params, blocks, state, condiff, beta, p_reward_correct)
    % World 1 ground truth: basicRL's own mechanism -- plain,
    % winner-take-all alpha update, no confidence-scaling, no
    % integration. This is what "truly fixed learning rate" means,
    % operationalized as a generative process. Identical to
    % check_RLsigma_integration_discriminability.m's copy of this
    % function, reused here so both scripts' ground truth matches exactly.
    alpha = params(1);
    sigma = params(3);
    n_trials = length(condiff);
    recoded_reward = NaN(n_trials, 1);
    q_0_0_trace = NaN(n_trials, 1);
    q_0_0 = 0.5;

    for n = 1:n_trials
        if n == 1 || blocks(n) ~= blocks(n-1)
            q_0_0 = 0.5;
        end

        belief_state = normcdf(condiff(n), 0, sigma);
        if condiff(n) < 0
            pi_0 = 1 - belief_state;
            pi_1 = belief_state;
        else
            pi_1 = belief_state;
            pi_0 = 1 - belief_state;
        end

        v_a0 = (pi_0 - pi_1) * q_0_0 + pi_1;
        v_a1 = 1 - v_a0;
        p_choice0 = 1 / (1 + exp(-beta * (v_a0 - v_a1)));
        choice_n = double(rand >= p_choice0);

        if choice_n == state(n)
            reward_n = double(rand < p_reward_correct);
        else
            reward_n = double(rand < (1 - p_reward_correct));
        end
        recoded_reward(n) = fitSlider_ALLmodels.recode_rewards_choice(reward_n, choice_n);

        % Plain (winner-take-all) alpha update -- the "fixed LR" mechanism.
        if pi_0 >= pi_1
            q_0_0 = q_0_0 + alpha * (recoded_reward(n) - q_0_0);
        else
            q_0_0 = q_0_0 + alpha * ((1 - recoded_reward(n)) - q_0_0);
        end
        q_0_0_trace(n) = q_0_0;
    end
end

function [recoded_reward, q_0_0_trace] = local_generate_world2_adaptive(params, blocks, state, condiff, beta, p_reward_correct)
    % World 2 ground truth: RLsigma's own mechanism -- belief-weighted
    % (pi_0*alpha / pi_1*alpha) update, no integration. This is what
    % "truly adaptive (confidence-scaled) learning rate" means,
    % operationalized as a generative process. Identical to
    % check_RLsigma_integration_discriminability.m's copy of this
    % function, reused here so both scripts' ground truth matches exactly.
    alpha = params(1);
    sigma = params(3);
    n_trials = length(condiff);
    recoded_reward = NaN(n_trials, 1);
    q_0_0_trace = NaN(n_trials, 1);
    q_0_0 = 0.5;

    for n = 1:n_trials
        if n == 1 || blocks(n) ~= blocks(n-1)
            q_0_0 = 0.5;
        end

        belief_state = normcdf(condiff(n), 0, sigma);
        if condiff(n) < 0
            pi_0 = 1 - belief_state;
            pi_1 = belief_state;
        else
            pi_1 = belief_state;
            pi_0 = 1 - belief_state;
        end

        v_a0 = (pi_0 - pi_1) * q_0_0 + pi_1;
        v_a1 = 1 - v_a0;
        p_choice0 = 1 / (1 + exp(-beta * (v_a0 - v_a1)));
        choice_n = double(rand >= p_choice0);

        if choice_n == state(n)
            reward_n = double(rand < p_reward_correct);
        else
            reward_n = double(rand < (1 - p_reward_correct));
        end
        recoded_reward(n) = fitSlider_ALLmodels.recode_rewards_choice(reward_n, choice_n);

        % Belief-weighted alpha update -- the "adaptive LR" mechanism.
        if pi_0 >= pi_1
            q_0_0 = q_0_0 + pi_0 * alpha * (recoded_reward(n) - q_0_0);
        else
            q_0_0 = q_0_0 + pi_1 * alpha * ((1 - recoded_reward(n)) - q_0_0);
        end
        q_0_0_trace(n) = q_0_0;
    end
end

function q_0_0_trace = local_track_Agent_integrated_givenRewards(params, blocks, recoded_reward, condiff)
    % Agent, WITH integration, as an observer/tracker: infers its belief
    % about reward contingency (obj.G, the Agent's own structural analog
    % of q_0_0 -- see script header) from an externally-given
    % (already-recoded) reward sequence, using the Agent's own real
    % learn()/integrate_voi() machinery, not an approximation of it.
    sigma = params(3);
    n_trials = length(condiff);
    q_0_0_trace = NaN(n_trials, 1);

    for n = 1:n_trials
        if n == 1 || blocks(n) ~= blocks(n-1)
            agent = Agent(); % fresh belief state at each block boundary, matching the other trackers' q_0_0=0.5 reset
            agent.sigma = sigma;
            agent.eval_ana = 0; % numerical belief update -- stable over this 25-trial block length
            agent.task_agent_analysis = 1; % WITH integration: learn() marginalizes over the set_o grid via integrate_voi
            agent.a_t = 0; % neutralises compute_action_dep_rew's action-contingent recoding -- recoded_reward already encodes "evidence for action 0" directly
        end

        agent.o_t = condiff(n); % exact (point) observation
        agent.learn(recoded_reward(n));
        q_0_0_trace(n) = agent.G; % == agent.E_mu_t in the eval_ana=0 branch used here
    end
end

function q_0_0_trace = local_track_Agent_noInt_givenRewards(params, blocks, recoded_reward, condiff)
    % Agent, WITHOUT integration, as an observer/tracker: same as above,
    % but learn() calls compute_q() directly on a single point-observation
    % belief instead of marginalizing over the set_o grid.
    sigma = params(3);
    n_trials = length(condiff);
    q_0_0_trace = NaN(n_trials, 1);

    for n = 1:n_trials
        if n == 1 || blocks(n) ~= blocks(n-1)
            agent = Agent();
            agent.sigma = sigma;
            agent.eval_ana = 0;
            agent.task_agent_analysis = 0; % WITHOUT integration: learn() uses compute_q() on the current point-observation pi_0/pi_1 directly
            agent.a_t = 0;
        end

        agent.p_s_giv_o(condiff(n)); % point-observation belief state (pi_0/pi_1) from the exact contrast difference
        agent.learn(recoded_reward(n));
        q_0_0_trace(n) = agent.G;
    end
end
