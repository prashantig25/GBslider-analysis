%% ========================================================================
%  Script: Does Integration Make the Agent Over-Smooth Genuine Learning?
%  ------------------------------------------------------------------------
%  Direct follow-up to check_RLsigma_integration_discriminability.m, for
%  the Agent instead of RLsigma. Earlier conversation argued that
%  integration should stay ON for the Agent (unlike basicRL/RLsigma,
%  where it's an optional technique that contaminates the fixed-vs-
%  adaptive comparison) because a genuinely Bayes-optimal observer that
%  doesn't know its own exact percept HAS to average over what it might
%  have perceived -- integration is constitutive of what the Agent is,
%  not a bolt-on. That argument was never demonstrated, only argued; this
%  script is the demonstration: does integration cause the Agent to
%  over-smooth genuine learning in a way that masks it, the same way it
%  was shown to make basicRL fake adaptive learning it doesn't have?
%  ------------------------------------------------------------------------
%  Method: identical ground truth to the RLsigma check -- two "fake
%  worlds" with KNOWN ground truth, at each of the five sigma values used
%  for the Agent simulations:
%    - World 1 (truly FIXED): generated by local_generate_world1_fixed --
%      basicRL's own mechanism (plain, winner-take-all alpha update), no
%      integration in the generator.
%    - World 2 (truly ADAPTIVE): generated by local_generate_world2_adaptive
%      -- RLsigma's own mechanism (confidence-weighted alpha update), no
%      integration in the generator.
%  Each world's reward sequence is then handed to the real Agent class as
%  an OBSERVER/tracker (not generating its own choices, just inferring
%  belief from the given reward sequence), once WITH integration
%  (local_track_Agent_integrated_givenRewards, Agent.learn's
%  integrate_voi path) and once WITHOUT (local_track_Agent_noInt_
%  givenRewards, Agent.learn's direct compute_q path) -- this uses the
%  Agent's own real learn()/compute_q()/integrate_voi() machinery, not an
%  approximation of it.
%  The tracked quantity is the Agent's own obj.G (== obj.E_mu_t in the
%  eval_ana=0 branch used here) -- its belief about the reward-
%  contingency parameter. This is the Agent's structural analog of
%  q_0_0: compute_valence's v_a_0 = (pi_0-pi_1)*E_mu_t+pi_1 is exactly
%  the same form as the world-generators' v_a0 = (pi_0-pi_1)*q_0_0+pi_1,
%  so obj.G is directly comparable to each world's true q_0_0_trace.
%  ------------------------------------------------------------------------
%  Design notes:
%  - Unlike the RLsigma check, there's no guaranteed exact overlap
%    between either world's true trajectory and either Agent tracker --
%    the Agent's Bayesian update rule is a genuinely different mechanism
%    from both basicRL's and RLsigma's alpha-update rules, so any
%    agreement or divergence seen here is informative, not a mechanical
%    identity.
%  - agent.a_t is fixed to 0 before each block so compute_action_dep_rew
%    doesn't re-recode the reward -- recoded_reward from the world
%    generators already encodes "evidence for action 0" directly, the
%    same convention the RLsigma trackers consume it with.
%  - agent.eval_ana = 0 (numerical belief update) for both trackers,
%    matching the RLsigma check's own numerical-path choice and avoiding
%    the growing-polynomial-degree instability eval_ana=1 has over long
%    blocks (not a concern at 25 trials, but kept consistent).
%  - A fresh Agent() is constructed at the start of every block (matching
%    the other trackers' q_0_0=0.5 reset) since the constructor correctly
%    resets the full numerical belief state (mu/product/mu_for_ev), not
%    just pi_0/pi_1.
%  - Same sigma sweep, same 100 sims x 4 blocks x 25 trials, same shared
%    Task()-generated state/contrast sequence per iteration as the
%    RLsigma check, for direct comparability between the two scripts'
%    figures.
%  ========================================================================
clc; clearvars; close all;

% PATH STUFF
currentDir = cd;
reqPath = 'GBslider-analysis';
pathParts = strsplit(currentDir, filesep);
if strcmp(pathParts{end}, reqPath)
    desiredPath = currentDir;
else
    desiredPath = createSavePaths(currentDir, reqPath);
end
save_fig_dir = fullfile(desiredPath, 'Agent', 'simfigures');
if ~exist(save_fig_dir, 'dir')
    mkdir(save_fig_dir);
end

%% PARAMETERS
sigma_values = [0.02, 0.04, 0.06, 0.08, 0.1]; % same sweep used for the Agent simulations
kappa_val = 20;   % unused by q_0_0_trace, kept for structural consistency with params
alpha_val = 0.1;  % learning rate for the world generators -- matches agentvars.m's own default
beta_val = 100;   % fixed softmax inverse temperature for economic choice -- matches agentvars.m's own default
p_reward_correct = 0.7; % true mu, Both condition (Agent/taskvars.m: condition==1 -> mu=0.7)

num_sims = 100;
num_blocks = 4;
num_trials_per_block = 25;
n_trials_total = num_blocks * num_trials_per_block;

%% SIMULATE
% Indexed [trial, block, sim, sigma].
world1_true_all = NaN(num_trials_per_block, num_blocks, num_sims, length(sigma_values));
world1_tracked_int_all = NaN(num_trials_per_block, num_blocks, num_sims, length(sigma_values));
world1_tracked_noInt_all = NaN(num_trials_per_block, num_blocks, num_sims, length(sigma_values));
world2_true_all = NaN(num_trials_per_block, num_blocks, num_sims, length(sigma_values));
world2_tracked_int_all = NaN(num_trials_per_block, num_blocks, num_sims, length(sigma_values));
world2_tracked_noInt_all = NaN(num_trials_per_block, num_blocks, num_sims, length(sigma_values));

for sg = 1:length(sigma_values)
    sigma_val = sigma_values(sg);
    params = [alpha_val, kappa_val, sigma_val];

    for sim = 1:num_sims
        % Shared Both-condition task sequence for this iteration -- both
        % worlds see the same state/contrast draws, for a fairer comparison.
        task = Task();
        task.condition = 1; % Both condition
        task.taskMu(0); % rangeMu = 0 -> fixed mu = 0.7 for condition 1

        state = NaN(n_trials_total, 1);
        condiff = NaN(n_trials_total, 1);
        blocks = NaN(n_trials_total, 1);
        for b = 1:num_blocks
            for t = 1:num_trials_per_block
                idx = (b-1)*num_trials_per_block + t;
                task.state_sample();
                task.contrast_sample();
                state(idx) = task.s_t;
                condiff(idx) = task.c_t;
                blocks(idx) = b;
            end
        end

        [reward_w1, q_true_w1] = local_generate_world1_fixed(params, blocks, state, condiff, beta_val, p_reward_correct);
        [reward_w2, q_true_w2] = local_generate_world2_adaptive(params, blocks, state, condiff, beta_val, p_reward_correct);

        q_tracked_w1_int = local_track_Agent_integrated_givenRewards(params, blocks, reward_w1, condiff);
        q_tracked_w1_noInt = local_track_Agent_noInt_givenRewards(params, blocks, reward_w1, condiff);
        q_tracked_w2_int = local_track_Agent_integrated_givenRewards(params, blocks, reward_w2, condiff);
        q_tracked_w2_noInt = local_track_Agent_noInt_givenRewards(params, blocks, reward_w2, condiff);

        world1_true_all(:, :, sim, sg) = reshape(q_true_w1, num_trials_per_block, num_blocks);
        world1_tracked_int_all(:, :, sim, sg) = reshape(q_tracked_w1_int, num_trials_per_block, num_blocks);
        world1_tracked_noInt_all(:, :, sim, sg) = reshape(q_tracked_w1_noInt, num_trials_per_block, num_blocks);
        world2_true_all(:, :, sim, sg) = reshape(q_true_w2, num_trials_per_block, num_blocks);
        world2_tracked_int_all(:, :, sim, sg) = reshape(q_tracked_w2_int, num_trials_per_block, num_blocks);
        world2_tracked_noInt_all(:, :, sim, sg) = reshape(q_tracked_w2_noInt, num_trials_per_block, num_blocks);
    end
end

%% PLOT
font_size = 12;
font_name = 'Arial';

world_labels = {'Using basicRL', 'Using RLsigma'};
true_data = {world1_true_all, world2_true_all};
tracked_int_data = {world1_tracked_int_all, world2_tracked_int_all};
tracked_noInt_data = {world1_tracked_noInt_all, world2_tracked_noInt_all};

%% ========================================================================
%  FIGURE 1: CROSS-WORLD DISCRIMINABILITY, SAME TRACKER
%  ------------------------------------------------------------------------
%  Same question as the RLsigma check: for a FIXED Agent tracker (no-
%  integration or with-integration), how separated are its World-1 (truly
%  fixed LR) and World-2 (truly adaptive LR) outputs? Rows = tracker type,
%  columns = sigma. Each panel overlays both worlds' true (dashed) and
%  tracked (solid) mean curves, colored by world (green = Using basicRL,
%  purple = Using RLsigma). SEM shading omitted for readability -- this
%  figure is about mean curve separation, not within-condition variability.
%  ========================================================================
world_color = {[0.4660, 0.6740, 0.1880], [0.4940, 0.1840, 0.5560]}; % green = Using basicRL, purple = Using RLsigma
tracker_labels = {'No Integration', 'Integration'};
tracked_data_by_tracker = {tracked_noInt_data, tracked_int_data};

figure('Position', [50, 50, 1500, 500]);
plot_idx = 1;
for tr = 1:length(tracker_labels)
    for sg = 1:length(sigma_values)
        ax = subplot(length(tracker_labels), length(sigma_values), plot_idx);
        hold on;

        h_true = gobjects(length(world_labels), 1);
        h_tracked = gobjects(length(world_labels), 1);
        for w = 1:length(world_labels)
            replicates_true = reshape(true_data{w}(:, :, :, sg), num_trials_per_block, num_blocks * num_sims);
            replicates_tracked = reshape(tracked_data_by_tracker{tr}{w}(:, :, :, sg), num_trials_per_block, num_blocks * num_sims);

            mean_true = mean(replicates_true, 2);
            mean_tracked = mean(replicates_tracked, 2);

            h_true(w) = plot(1:num_trials_per_block, mean_true, '--', 'Color', world_color{w}, 'LineWidth', 1);
            h_tracked(w) = plot(1:num_trials_per_block, mean_tracked, '-', 'Color', world_color{w}, 'LineWidth', 1.5);
        end

        title(sprintf('%s, sigma=%.2f', tracker_labels{tr}, sigma_values(sg)), 'FontWeight', 'normal', 'FontSize', font_size);
        if tr == length(tracker_labels)
            xlabel('Trial (within block)');
        end
        if sg == 1
            ylabel('Belief (G)');
        end
        set(ax, 'FontName', font_name, 'FontSize', font_size, 'LineWidth', 1, 'Color', 'none');
        box off;
        ylim([0, 1]);
        plot_idx = plot_idx + 1;
    end
end
legend([h_true(1), h_tracked(1), h_true(2), h_tracked(2)], ...
    {'Using basicRL: true', 'Using basicRL: tracked', 'Using RLsigma: true', 'Using RLsigma: tracked'}, ...
    'Position', [0.92, 0.4, 0.07, 0.15], 'Box', 'off', 'Color', 'none');
sgtitle(sprintf('Agent Discriminability Check: World 1 (basicRL) vs World 2 (RLsigma) (alpha=%.2f)', alpha_val), 'FontWeight', 'bold');

exportgraphics(gcf, fullfile(save_fig_dir, 'Agent_integration_discriminability_crossWorld.pdf'), 'ContentType', 'vector');

%% ========================================================================
%  FIGURE 2: SIGNED ESTIMATION ERROR (TRUE - TRACKED), BY SIGMA
%  ------------------------------------------------------------------------
%  Same construction as the RLsigma check's Figure 2: per-replicate signed
%  error (true belief minus tracked belief), averaged over the 25 trials
%  within a block, then mean/SEM across all replicates, for each (sigma,
%  tracking setting) combination. Positive = Agent UNDERESTIMATES the true
%  belief; negative = OVERESTIMATES. Rows = tracker type, each row a
%  grouped bar chart (5 sigma groups x 2 bars: Using basicRL, Using
%  RLsigma). Reading discriminability: within a subplot (tracker fixed),
%  compare the two bars at the same sigma -- if they're about the same
%  height, the Agent's bias cancels out in the World2-minus-World1
%  subtraction and it still separates the two worlds despite being
%  biased; if they differ, that's the discriminability-erosion amount.
%  ========================================================================
mean_error_noInt = NaN(length(sigma_values), length(world_labels));
sem_error_noInt = NaN(length(sigma_values), length(world_labels));
mean_error_int = NaN(length(sigma_values), length(world_labels));
sem_error_int = NaN(length(sigma_values), length(world_labels));

for w = 1:length(world_labels)
    for sg = 1:length(sigma_values)
        replicates_true = reshape(true_data{w}(:, :, :, sg), num_trials_per_block, num_blocks * num_sims);
        replicates_int = reshape(tracked_int_data{w}(:, :, :, sg), num_trials_per_block, num_blocks * num_sims);
        replicates_noInt = reshape(tracked_noInt_data{w}(:, :, :, sg), num_trials_per_block, num_blocks * num_sims);

        per_replicate_error_noInt = mean(replicates_true - replicates_noInt, 1); % 1 x replicates, averaged over trials
        per_replicate_error_int = mean(replicates_true - replicates_int, 1);

        mean_error_noInt(sg, w) = mean(per_replicate_error_noInt);
        sem_error_noInt(sg, w) = std(per_replicate_error_noInt) / sqrt(length(per_replicate_error_noInt));
        mean_error_int(sg, w) = mean(per_replicate_error_int);
        sem_error_int(sg, w) = std(per_replicate_error_int) / sqrt(length(per_replicate_error_int));
    end
end

error_mean_by_tracker = {mean_error_noInt, mean_error_int};
error_sem_by_tracker = {sem_error_noInt, sem_error_int};

figure('Position', [50, 50, 900, 700]);
for tr = 1:length(tracker_labels)
    subplot(length(tracker_labels), 1, tr);
    hold on;

    bar_means = error_mean_by_tracker{tr}; % sigma x [Using basicRL, Using RLsigma]
    bar_sems = error_sem_by_tracker{tr};

    b = bar(1:length(sigma_values), bar_means);
    b(1).FaceColor = world_color{1};
    b(2).FaceColor = world_color{2};
    for k = 1:length(b)
        errorbar(b(k).XEndPoints, b(k).YData, bar_sems(:, k)', 'k', 'LineStyle', 'none', 'LineWidth', 1);
    end
    yline(0, '-k', 'LineWidth', 0.5);

    set(gca, 'XTick', 1:length(sigma_values), 'XTickLabel', arrayfun(@(x) sprintf('%.2f', x), sigma_values, 'UniformOutput', false));
    xlabel('Sigma');
    ylabel('Signed error (true - tracked)');
    title(tracker_labels{tr}, 'FontWeight', 'normal', 'FontSize', font_size);
    set(gca, 'FontName', font_name, 'FontSize', font_size, 'LineWidth', 1, 'Color', 'none');
    box off;
    if tr == 1
        legend(world_labels, 'Location', 'northwest', 'Box', 'off');
    end
end
sgtitle(sprintf('Agent Signed Estimation Error: True Belief Minus Agent-Tracked Belief (alpha=%.2f)', alpha_val), 'FontWeight', 'bold');

