%% ========================================================================
%  Script: Does Integration Let RLsigma Tell Truly Fixed vs Truly
%  Adaptive Learning Rates Apart?
%  ------------------------------------------------------------------------
%  Diagnostic for the question raised in conversation: integration was
%  shown to make basicRL (a genuinely fixed-step-size model) mimic
%  adaptive (confidence-scaled) learning it doesn't actually have. Does
%  the same thing happen to RLsigma -- i.e. does integration dilute
%  RLsigma's own, already-built-in confidence-weighting signature, making
%  it harder to tell a truly fixed-rate learner from a truly adaptive-rate
%  learner?
%  ------------------------------------------------------------------------
%  Method: build two "fake worlds" with KNOWN ground truth, at each of the
%  five sigma values used for the Agent simulations:
%    - World 1 (truly FIXED): a synthetic subject generated by
%      local_generate_world1_fixed -- literally basicRL's own mechanism
%      (plain, winner-take-all alpha update, no confidence-scaling at
%      all), with NO integration in the generator itself.
%    - World 2 (truly ADAPTIVE): a synthetic subject generated by
%      local_generate_world2_adaptive -- RLsigma's own mechanism
%      (confidence-weighted pi_0*alpha / pi_1*alpha update), again with NO
%      integration in the generator -- a "pure" adaptive ground truth.
%  Each world's generator also returns its OWN true belief trajectory
%  (q_0_0_trace) -- the trajectory that genuinely occurred -- as a
%  reference for what "correctly recovering the ground truth" should look
%  like.
%  Then, each world's reward sequence is handed to RLsigma as an
%  OBSERVER/tracker (not re-generating its own choices -- just inferring
%  belief from the given reward sequence, like an NLL function does),
%  once WITH integration (local_track_RLsigma_integrated_givenRewards)
%  and once WITHOUT (local_track_RLsigma_pointObs_givenRewards).
%  If integration is fine, RLsigma-with-integration's tracked curve should
%  closely follow World 1's true (flat, non-adaptive-looking) trajectory
%  for World 1's data, and World 2's true (adaptive-looking) trajectory
%  for World 2's data -- i.e. it should still clearly tell the two worlds
%  apart. If integration dilutes RLsigma's signature (the same problem
%  found for basicRL), the two worlds' tracked-with-integration curves
%  will look more similar to each other than their true generators
%  actually were.
%  ------------------------------------------------------------------------
%  Design notes:
%  - Plots the clean underlying belief (q_0_0_trace), not a simulated
%    slider report (mu_hat) -- this diagnostic is about the shape of the
%    learning dynamics itself, not report noise, so kappa's Beta-sampling
%    noise is left out as an irrelevant extra source of variability here.
%  - alpha, beta, kappa are not swept -- defaulted to 0.1, 100, and 20
%    respectively (alpha/beta matching Agent/agentvars.m's own defaults;
%    kappa is unused by the plotted quantity but kept in params for
%    structural consistency with the other simulate_* functions).
%  - Task()/taskvars() (Agent/Task.m, Agent/taskvars.m) generate the
%    state/contrast sequence each trial -- condition=1 maps to mu=0.7 (the
%    "Both" condition), matching the real task's generative process. Both
%    worlds share the SAME generated task sequence per (sigma, simulation)
%    iteration, for a fairer comparison.
%  - Each simulation's 4 blocks are independent replicate learning curves
%    (belief resets to 0.5 at the start of every block) -- reshaped and
%    pooled with the 50 simulations into 200 total replicates per (world,
%    tracking setting, sigma) combination for the mean/SEM.
%  ========================================================================
clc; clearvars; close all;

% PATH STUFF
currentDir = cd;
reqPath = 'Reward-learning-analysis (code_review)';
pathParts = strsplit(currentDir, filesep);
if strcmp(pathParts{end}, reqPath)
    desiredPath = currentDir;
else
    desiredPath = createSavePaths(currentDir, reqPath);
end
save_fig_dir = fullfile(desiredPath, 'Agent', 'simfigures');
if ~exist(save_fig_dir, 'dir')
    mkdir(save_fig_dir);
end

%% PARAMETERS
sigma_values = [0.02, 0.04, 0.06, 0.08, 0.1]; % same sweep used for the Agent simulations
kappa_val = 20;   % unused by q_0_0_trace, kept for structural consistency with params
alpha_val = 0.1;  % learning rate -- matches agentvars.m's own default
beta_val = 100;   % fixed softmax inverse temperature for economic choice -- matches agentvars.m's own default
p_reward_correct = 0.7; % true mu, Both condition (Agent/taskvars.m: condition==1 -> mu=0.7)

num_sims = 100;
num_blocks = 4;
num_trials_per_block = 25;
n_trials_total = num_blocks * num_trials_per_block;

%% SIMULATE
% Indexed [trial, block, sim, sigma].
world1_true_all = NaN(num_trials_per_block, num_blocks, num_sims, length(sigma_values));
world1_tracked_int_all = NaN(num_trials_per_block, num_blocks, num_sims, length(sigma_values));
world1_tracked_noInt_all = NaN(num_trials_per_block, num_blocks, num_sims, length(sigma_values));
world2_true_all = NaN(num_trials_per_block, num_blocks, num_sims, length(sigma_values));
world2_tracked_int_all = NaN(num_trials_per_block, num_blocks, num_sims, length(sigma_values));
world2_tracked_noInt_all = NaN(num_trials_per_block, num_blocks, num_sims, length(sigma_values));

for sg = 1:length(sigma_values)
    sigma_val = sigma_values(sg);
    params = [alpha_val, kappa_val, sigma_val];

    for sim = 1:num_sims
        % Shared Both-condition task sequence for this iteration -- both
        % worlds see the same state/contrast draws, for a fairer comparison.
        task = Task();
        task.condition = 1; % Both condition
        task.taskMu(0); % rangeMu = 0 -> fixed mu = 0.7 for condition 1

        state = NaN(n_trials_total, 1);
        condiff = NaN(n_trials_total, 1);
        blocks = NaN(n_trials_total, 1);
        for b = 1:num_blocks
            for t = 1:num_trials_per_block
                idx = (b-1)*num_trials_per_block + t;
                task.state_sample();
                task.contrast_sample();
                state(idx) = task.s_t;
                condiff(idx) = task.c_t;
                blocks(idx) = b;
            end
        end

        [reward_w1, q_true_w1] = local_generate_world1_fixed(params, blocks, state, condiff, beta_val, p_reward_correct);
        [reward_w2, q_true_w2] = local_generate_world2_adaptive(params, blocks, state, condiff, beta_val, p_reward_correct);

        q_tracked_w1_int = local_track_RLsigma_integrated_givenRewards(params, blocks, reward_w1, condiff);
        q_tracked_w1_noInt = local_track_RLsigma_pointObs_givenRewards(params, blocks, reward_w1, condiff);
        q_tracked_w2_int = local_track_RLsigma_integrated_givenRewards(params, blocks, reward_w2, condiff);
        q_tracked_w2_noInt = local_track_RLsigma_pointObs_givenRewards(params, blocks, reward_w2, condiff);

        world1_true_all(:, :, sim, sg) = reshape(q_true_w1, num_trials_per_block, num_blocks);
        world1_tracked_int_all(:, :, sim, sg) = reshape(q_tracked_w1_int, num_trials_per_block, num_blocks);
        world1_tracked_noInt_all(:, :, sim, sg) = reshape(q_tracked_w1_noInt, num_trials_per_block, num_blocks);
        world2_true_all(:, :, sim, sg) = reshape(q_true_w2, num_trials_per_block, num_blocks);
        world2_tracked_int_all(:, :, sim, sg) = reshape(q_tracked_w2_int, num_trials_per_block, num_blocks);
        world2_tracked_noInt_all(:, :, sim, sg) = reshape(q_tracked_w2_noInt, num_trials_per_block, num_blocks);
    end
end

%% PLOT
font_size = 12;
font_name = 'Arial';

world_labels = {'Using basicRL', 'Using RLsigma'};
true_data = {world1_true_all, world2_true_all};
tracked_int_data = {world1_tracked_int_all, world2_tracked_int_all};
tracked_noInt_data = {world1_tracked_noInt_all, world2_tracked_noInt_all};

% Note: the "Using RLsigma" true-generator trajectory is mathematically
% identical to its own no-integration tracker (same point-estimate
% belief, same confidence-weighted update, same reward sequence), so in
% the "No Integration" row below its dashed true line sits exactly on top
% of (and is invisible behind) its solid tracked line -- this is
% confirmed, not an error, and is exactly why the gap-bar figure further
% down quantifies it directly rather than relying on it showing up
% visually.

%% ========================================================================
%  FIGURE 1: CROSS-WORLD DISCRIMINABILITY, SAME TRACKER
%  ------------------------------------------------------------------------
%  The question this diagnostic is actually about: for a FIXED tracker
%  (no-integration or with-integration), how separated are its World-1
%  (truly fixed LR) and World-2 (truly adaptive LR) outputs? That
%  cross-world separation -- not tracking accuracy against truth -- is
%  "discriminability," so it has to be compared across worlds within the
%  same tracker, not across trackers within the same world (see
%  conversation).
%  Rows = tracker type (No Integration / Integration), columns = sigma.
%  Each panel overlays both worlds' true (dashed) and tracked (solid)
%  mean curves, colored by world -- reusing simulate_basicRL_mu_curves.m's
%  model-identity colors (green = Using basicRL, purple = Using RLsigma)
%  since color here encodes world, not tracker. SEM shading is omitted
%  (4 overlapping bands would be unreadable); this figure is about mean
%  curve separation, not within-condition variability.
%  ========================================================================
world_color = {[0.4660, 0.6740, 0.1880], [0.4940, 0.1840, 0.5560]}; % green = Using basicRL, purple = Using RLsigma
tracker_labels = {'No Integration', 'Integration'};
tracked_data_by_tracker = {tracked_noInt_data, tracked_int_data};

figure('Position', [50, 50, 1500, 500]);
plot_idx = 1;
for tr = 1:length(tracker_labels)
    for sg = 1:length(sigma_values)
        ax = subplot(length(tracker_labels), length(sigma_values), plot_idx);
        hold on;

        h_true = gobjects(length(world_labels), 1);
        h_tracked = gobjects(length(world_labels), 1);
        for w = 1:length(world_labels)
            replicates_true = reshape(true_data{w}(:, :, :, sg), num_trials_per_block, num_blocks * num_sims);
            replicates_tracked = reshape(tracked_data_by_tracker{tr}{w}(:, :, :, sg), num_trials_per_block, num_blocks * num_sims);

            mean_true = mean(replicates_true, 2);
            mean_tracked = mean(replicates_tracked, 2);

            h_true(w) = plot(1:num_trials_per_block, mean_true, '--', 'Color', world_color{w}, 'LineWidth', 1);
            h_tracked(w) = plot(1:num_trials_per_block, mean_tracked, '-', 'Color', world_color{w}, 'LineWidth', 1.5);
        end

        title(sprintf('%s, sigma=%.2f', tracker_labels{tr}, sigma_values(sg)), 'FontWeight', 'normal', 'FontSize', font_size);
        if tr == length(tracker_labels)
            xlabel('Trial (within block)');
        end
        if sg == 1
            ylabel('Belief (q\_0\_0)');
        end
        set(ax, 'FontName', font_name, 'FontSize', font_size, 'LineWidth', 1, 'Color', 'none');
        box off;
        ylim([0, 1]);
        plot_idx = plot_idx + 1;
    end
end
legend([h_true(1), h_tracked(1), h_true(2), h_tracked(2)], ...
    {'Using basicRL: true', 'Using basicRL: tracked', 'Using RLsigma: true', 'Using RLsigma: tracked'}, ...
    'Position', [0.92, 0.4, 0.07, 0.15], 'Box', 'off', 'Color', 'none');
sgtitle(sprintf('Discriminability Check: Same Tracker, World 1 (basicRL) vs World 2 (RLsigma) (kappa=%.0f, alpha=%.2f)', kappa_val, alpha_val), 'FontWeight', 'bold');

exportgraphics(gcf, fullfile(save_fig_dir, 'RLsigma_integration_discriminability_crossWorld.pdf'), 'ContentType', 'vector');

%% ========================================================================
%  FIGURE 2: SIGNED ESTIMATION ERROR (TRUE - TRACKED), BY SIGMA
%  ------------------------------------------------------------------------
%  For each replicate (block x sim), the signed error (true belief minus
%  tracked belief) is averaged across the 25 trials within that block,
%  collapsing to one scalar per replicate -- then the mean and SEM of that
%  per-replicate scalar is taken across all replicates, for each (sigma,
%  tracking setting) combination. A positive bar means the tracker
%  UNDERESTIMATES the true belief on average (true > tracked); negative
%  means it OVERESTIMATES. Rows = tracker type (No Integration /
%  Integration, mirroring Figure 1's row grouping), each row a single
%  grouped bar chart (5 sigma groups x 2 bars: Using basicRL, Using
%  RLsigma, colored with Figure 1's world colors) instead of 5 separate
%  line-plot panels.
%  Reading discriminability off this figure: within a subplot (tracker
%  fixed), compare the two bars at the same sigma. If they're about the
%  same height, that tracker's bias cancels out in the World2-minus-
%  World1 subtraction and it still separates the two worlds fine despite
%  being biased; if they differ, that difference is algebraically exactly
%  how much that tracker's between-world gap deviates from the TRUE
%  between-world gap (see conversation) -- i.e. it IS the
%  discriminability-erosion amount, read directly as two adjacent bars
%  instead of a subtraction across two separate subplots.
%  ========================================================================
mean_error_noInt = NaN(length(sigma_values), length(world_labels));
sem_error_noInt = NaN(length(sigma_values), length(world_labels));
mean_error_int = NaN(length(sigma_values), length(world_labels));
sem_error_int = NaN(length(sigma_values), length(world_labels));

for w = 1:length(world_labels)
    for sg = 1:length(sigma_values)
        replicates_true = reshape(true_data{w}(:, :, :, sg), num_trials_per_block, num_blocks * num_sims);
        replicates_int = reshape(tracked_int_data{w}(:, :, :, sg), num_trials_per_block, num_blocks * num_sims);
        replicates_noInt = reshape(tracked_noInt_data{w}(:, :, :, sg), num_trials_per_block, num_blocks * num_sims);

        per_replicate_error_noInt = mean(replicates_true - replicates_noInt, 1); % 1 x replicates, averaged over trials
        per_replicate_error_int = mean(replicates_true - replicates_int, 1);

        mean_error_noInt(sg, w) = mean(per_replicate_error_noInt);
        sem_error_noInt(sg, w) = std(per_replicate_error_noInt) / sqrt(length(per_replicate_error_noInt));
        mean_error_int(sg, w) = mean(per_replicate_error_int);
        sem_error_int(sg, w) = std(per_replicate_error_int) / sqrt(length(per_replicate_error_int));
    end
end

error_mean_by_tracker = {mean_error_noInt, mean_error_int};
error_sem_by_tracker = {sem_error_noInt, sem_error_int};

figure('Position', [50, 50, 900, 700]);
for tr = 1:length(tracker_labels)
    subplot(length(tracker_labels), 1, tr);
    hold on;

    bar_means = error_mean_by_tracker{tr}; % sigma x [Using basicRL, Using RLsigma]
    bar_sems = error_sem_by_tracker{tr};

    b = bar(1:length(sigma_values), bar_means);
    b(1).FaceColor = world_color{1};
    b(2).FaceColor = world_color{2};
    for k = 1:length(b)
        errorbar(b(k).XEndPoints, b(k).YData, bar_sems(:, k)', 'k', 'LineStyle', 'none', 'LineWidth', 1);
    end
    yline(0, '-k', 'LineWidth', 0.5);

    set(gca, 'XTick', 1:length(sigma_values), 'XTickLabel', arrayfun(@(x) sprintf('%.2f', x), sigma_values, 'UniformOutput', false));
    xlabel('Sigma');
    ylabel('Signed error (true - tracked)');
    title(tracker_labels{tr}, 'FontWeight', 'normal', 'FontSize', font_size);
    set(gca, 'FontName', font_name, 'FontSize', font_size, 'LineWidth', 1, 'Color', 'none');
    box off;
    if tr == 1
        legend(world_labels, 'Location', 'northwest', 'Box', 'off');
    end
end
sgtitle(sprintf('Signed Estimation Error: True Belief Minus RLsigma-Tracked Belief (kappa=%.0f, alpha=%.2f)', kappa_val, alpha_val), 'FontWeight', 'bold');

exportgraphics(gcf, fullfile(save_fig_dir, 'RLsigma_integration_signedError_bySigma.pdf'), 'ContentType', 'vector');

%% ========================================================================
%  Local functions
%  ========================================================================
function [recoded_reward, q_0_0_trace] = local_generate_world1_fixed(params, blocks, state, condiff, beta, p_reward_correct)
    % World 1 ground truth: basicRL's own mechanism -- plain,
    % winner-take-all alpha update, no confidence-scaling, no
    % integration. This is what "truly fixed learning rate" means,
    % operationalized as a generative process.
    alpha = params(1);
    sigma = params(3);
    n_trials = length(condiff);
    recoded_reward = NaN(n_trials, 1);
    q_0_0_trace = NaN(n_trials, 1);
    q_0_0 = 0.5;

    for n = 1:n_trials
        if n == 1 || blocks(n) ~= blocks(n-1)
            q_0_0 = 0.5;
        end

        belief_state = normcdf(condiff(n), 0, sigma);
        if condiff(n) < 0
            pi_0 = 1 - belief_state;
            pi_1 = belief_state;
        else
            pi_1 = belief_state;
            pi_0 = 1 - belief_state;
        end

        v_a0 = (pi_0 - pi_1) * q_0_0 + pi_1;
        v_a1 = 1 - v_a0;
        p_choice0 = 1 / (1 + exp(-beta * (v_a0 - v_a1)));
        choice_n = double(rand >= p_choice0);

        if choice_n == state(n)
            reward_n = double(rand < p_reward_correct);
        else
            reward_n = double(rand < (1 - p_reward_correct));
        end
        recoded_reward(n) = fitSlider_ALLmodels.recode_rewards_choice(reward_n, choice_n);

        % Plain (winner-take-all) alpha update -- the "fixed LR" mechanism.
        if pi_0 >= pi_1
            q_0_0 = q_0_0 + alpha * (recoded_reward(n) - q_0_0);
        else
            q_0_0 = q_0_0 + alpha * ((1 - recoded_reward(n)) - q_0_0);
        end
        q_0_0_trace(n) = q_0_0;
    end
end

function [recoded_reward, q_0_0_trace] = local_generate_world2_adaptive(params, blocks, state, condiff, beta, p_reward_correct)
    % World 2 ground truth: RLsigma's own mechanism -- belief-weighted
    % (pi_0*alpha / pi_1*alpha) update, no integration. This is what
    % "truly adaptive (confidence-scaled) learning rate" means,
    % operationalized as a generative process.
    alpha = params(1);
    sigma = params(3);
    n_trials = length(condiff);
    recoded_reward = NaN(n_trials, 1);
    q_0_0_trace = NaN(n_trials, 1);
    q_0_0 = 0.5;

    for n = 1:n_trials
        if n == 1 || blocks(n) ~= blocks(n-1)
            q_0_0 = 0.5;
        end

        belief_state = normcdf(condiff(n), 0, sigma);
        if condiff(n) < 0
            pi_0 = 1 - belief_state;
            pi_1 = belief_state;
        else
            pi_1 = belief_state;
            pi_0 = 1 - belief_state;
        end

        v_a0 = (pi_0 - pi_1) * q_0_0 + pi_1;
        v_a1 = 1 - v_a0;
        p_choice0 = 1 / (1 + exp(-beta * (v_a0 - v_a1)));
        choice_n = double(rand >= p_choice0);

        if choice_n == state(n)
            reward_n = double(rand < p_reward_correct);
        else
            reward_n = double(rand < (1 - p_reward_correct));
        end
        recoded_reward(n) = fitSlider_ALLmodels.recode_rewards_choice(reward_n, choice_n);

        % Belief-weighted alpha update -- the "adaptive LR" mechanism.
        if pi_0 >= pi_1
            q_0_0 = q_0_0 + pi_0 * alpha * (recoded_reward(n) - q_0_0);
        else
            q_0_0 = q_0_0 + pi_1 * alpha * ((1 - recoded_reward(n)) - q_0_0);
        end
        q_0_0_trace(n) = q_0_0;
    end
end

function q_0_0_trace = local_track_RLsigma_integrated_givenRewards(params, blocks, recoded_reward, condiff)
    % RLsigma, WITH integration, as an observer/tracker: infers belief
    % from an externally-given (already-recoded) reward sequence, rather
    % than generating its own choices -- mirrors simulate_RLsigma_
    % integrated_choice's belief-update pass exactly, minus the
    % choice-generation pass.
    alpha = params(1);
    sigma = params(3);
    n_trials = length(condiff);
    q_0_0_trace = NaN(n_trials, 1);
    q_0_0 = 0.5;

    set_o = linspace(-0.1, 0.1, 20);
    n_o = length(set_o);
    agent = Agent();
    agent.sigma = sigma;

    for n = 1:n_trials
        if n == 1 || blocks(n) ~= blocks(n-1)
            q_0_0 = 0.5;
        end

        p_o_given_u = fitSlider_ALLmodels.observation_weights(set_o, condiff(n), sigma);
        voi_matrix = NaN(n_o, 2);
        for i = 1:n_o
            agent.p_s_giv_o(set_o(i));
            pi_0 = agent.pi_0;
            pi_1 = agent.pi_1;

            q_sim = q_0_0;
            if pi_0 >= pi_1
                q_sim = q_sim + pi_0 * alpha * (recoded_reward(n) - q_sim);
            else
                q_sim = q_sim + pi_1 * alpha * ((1 - recoded_reward(n)) - q_sim);
            end
            voi_matrix(i, :) = [q_sim, 1 - q_sim];
        end
        q_0_0 = sum(voi_matrix(:,1) .* p_o_given_u');
        q_0_0_trace(n) = q_0_0;
    end
end

function q_0_0_trace = local_track_RLsigma_pointObs_givenRewards(params, blocks, recoded_reward, condiff)
